// Command pin fetches the SHA512 lists of NetBSD releases, and the newest
// dated CA bundle curl extracts from Mozilla's store, and prints
// netbsd/versions.bzl, the checksum table the repository rules verify
// downloads against.
//
//	go run ./tools/pin 11.1/amd64 11.1/aarch64 > netbsd/versions.bzl
package main

import (
	"bufio"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
)

const (
	mirror = "https://cdn.netbsd.org/pub/NetBSD"
	// https://curl.se/docs/caextract.html lists the dated, immutable copies.
	curlCAPage = "https://curl.se/docs/caextract.html"
	curlCABase = "https://curl.se/ca/"
)

var curlCARE = regexp.MustCompile(`/ca/(cacert-(\d{4}-\d{2}-\d{2})\.pem)"`)

// Sets the rules use; everything else in the release is ignored.
var (
	sourceSets = []string{"src.tgz", "syssrc.tgz", "sharesrc.tgz", "gnusrc.tgz"}
	lineRE     = regexp.MustCompile(`^SHA512 \(([^)]+)\) = ([0-9a-f]{128})$`)
)

// ports maps the rules' architecture names to NetBSD release directories and
// the binary sets taken from them.
var ports = map[string]struct {
	dir  string
	sets []string
}{
	"amd64":   {"amd64", []string{"kern-GENERIC.tar.xz", "base.tar.xz", "etc.tar.xz"}},
	"aarch64": {"evbarm-aarch64", []string{"kern-GENERIC64.tar.xz", "base.tar.xz", "etc.tar.xz"}},
}

func fetchSums(url string) (map[string]string, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	sums := map[string]string{}
	sc := bufio.NewScanner(resp.Body)
	for sc.Scan() {
		if m := lineRE.FindStringSubmatch(sc.Text()); m != nil {
			raw, _ := hex.DecodeString(m[2])
			sums[m[1]] = "sha512-" + base64.StdEncoding.EncodeToString(raw)
		}
	}
	return sums, sc.Err()
}

func get(url string) (string, error) {
	resp, err := http.Get(url)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return "", fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	var b strings.Builder
	_, err = bufio.NewReader(resp.Body).WriteTo(&b)
	return b.String(), err
}

// latestCurlCA returns the newest dated bundle's file name, date and
// SHA-256 as curl publishes them.
func latestCurlCA() (file, date, sha string, err error) {
	page, err := get(curlCAPage)
	if err != nil {
		return "", "", "", err
	}
	m := curlCARE.FindStringSubmatch(page) // the page lists newest first
	if m == nil {
		return "", "", "", fmt.Errorf("%s: no dated cacert files found", curlCAPage)
	}
	sum, err := get(curlCABase + m[1] + ".sha256")
	if err != nil {
		return "", "", "", err
	}
	fields := strings.Fields(sum)
	if len(fields) == 0 || len(fields[0]) != 64 {
		return "", "", "", fmt.Errorf("unexpected checksum file %q", sum)
	}
	return m[1], m[2], fields[0], nil
}

func pick(sums map[string]string, names []string, where string) (map[string]string, error) {
	out := map[string]string{}
	for _, n := range names {
		s, ok := sums[n]
		if !ok {
			return nil, fmt.Errorf("%s: no checksum for %s", where, n)
		}
		out[n] = s
	}
	return out, nil
}

func writeDict(b *strings.Builder, indent string, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "%s%q: %q,\n", indent, k, m[k])
	}
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: pin VERSION/ARCH...")
		os.Exit(2)
	}
	archs := map[string][]string{}
	var versions []string
	for _, a := range os.Args[1:] {
		v, arch, ok := strings.Cut(a, "/")
		if !ok {
			fmt.Fprintf(os.Stderr, "pin: %q is not VERSION/ARCH\n", a)
			os.Exit(2)
		}
		if _, seen := archs[v]; !seen {
			versions = append(versions, v)
		}
		archs[v] = append(archs[v], arch)
	}
	sort.Strings(versions)

	var b strings.Builder
	b.WriteString("# Copyright 2026 Moriyoshi Koizumi\n# SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("\"\"\"Checksums of NetBSD release files. Generated by //tools/pin; do not edit.\"\"\"\n\n")
	fmt.Fprintf(&b, "MIRROR = %q\n\n", mirror)
	b.WriteString("RELEASES = {\n")
	for _, v := range versions {
		src, err := fetchSums(fmt.Sprintf("%s/NetBSD-%s/source/sets/SHA512", mirror, v))
		if err == nil {
			src, err = pick(src, sourceSets, v+" source")
		}
		if err != nil {
			fmt.Fprintln(os.Stderr, "pin:", err)
			os.Exit(1)
		}
		fmt.Fprintf(&b, "    %q: {\n        \"source\": {\n", v)
		writeDict(&b, "            ", src)
		b.WriteString("        },\n        \"sets\": {\n")
		sort.Strings(archs[v])
		for _, arch := range archs[v] {
			port, ok := ports[arch]
			if !ok {
				fmt.Fprintf(os.Stderr, "pin: unknown arch %q\n", arch)
				os.Exit(2)
			}
			sets, err := fetchSums(fmt.Sprintf("%s/NetBSD-%s/%s/binary/sets/SHA512", mirror, v, port.dir))
			if err == nil {
				sets, err = pick(sets, port.sets, v+"/"+arch)
			}
			if err != nil {
				fmt.Fprintln(os.Stderr, "pin:", err)
				os.Exit(1)
			}
			fmt.Fprintf(&b, "            %q: {\n", arch)
			writeDict(&b, "                ", sets)
			b.WriteString("            },\n")
		}
		b.WriteString("        },\n    },\n")
	}
	b.WriteString("}\n")

	file, date, sha, err := latestCurlCA()
	if err != nil {
		fmt.Fprintln(os.Stderr, "pin:", err)
		os.Exit(1)
	}
	b.WriteString("\n# The Mozilla CA bundle as extracted by curl (https://curl.se/docs/caextract.html).\n")
	fmt.Fprintf(&b, "CURL_CA_BUNDLE = {\n    \"date\": %q,\n    \"sha256\": %q,\n    \"url\": %q,\n}\n", date, sha, curlCABase+file)
	os.Stdout.WriteString(b.String())
}
